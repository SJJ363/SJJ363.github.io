const IDS = new Set(CARDS.map((c) => c.id));

/* ── The lookup every consumer uses ─────────────────────────────
   Falls back to the home card rather than to a missing file: a page
   with the wrong card still previews, a page with a 404 image
   previews as bare text, which is the bug this file exists to fix. */
function cardFor(id) {
  return `/assets/og/${IDS.has(id) ? id : "home"}.png`;
}

/* ══════════════════════════════════════════════════════════════
   RENDERING
   ══════════════════════════════════════════════════════════════ */

const esc = (s = "") =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/* Headlines are set by hand here, so a size table beats a measuring
   pass: the longest title in the list is "Claims & Underwriting". */
function titleSize(t) {
  const n = t.length;
  if (n <= 14) return 112;
  if (n <= 20) return 94;
  if (n <= 26) return 80;
  return 68;
}

