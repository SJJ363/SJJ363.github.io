#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════
   og.js — the social sharing cards
   ══════════════════════════════════════════════════════════════

   WHY THIS EXISTS AT ALL

   The site shipped with `og:image` pointing at `assets/og.svg`. It was
   a perfectly good 1200×630 card and no link preview anywhere ever
   rendered it: **no major scraper rasterizes SVG.** Facebook (which
   LinkedIn's and most others' crawlers imitate), X, Slack, Discord and
   Apple's iMessage fetcher all accept PNG / JPEG / GIF / WEBP and
   silently drop anything else. A vector card is not a small card or a
   slow card — it is no card, and the link degrades to bare blue text.

   So the deliverable is raster. This script renders each card to PNG
   through headless Chrome, which gets us the site's real web fonts
   (Newsreader + Libre Franklin) instead of a system-serif approximation.

   WHY THE CARDS ARE STATIC AND COMMITTED

   Everything else under `scripts/` is regenerated by CI on every run.
   These are not, deliberately: rendering needs a browser binary, and
   `news.yml` should not grow a Chrome install to redraw artwork whose
   text — a section name and the masthead — does not change between
   runs. The *page-specific* half of a preview card (the headline and
   the blurb the platform prints beside the image) comes from
   `og:title` / `og:description`, which seo.js already writes per page.
   The image carries the brand and the section.

   That is why there is one card per *page type*, not per page:
   ~200 company pages sharing one "Companies" card is the same trade
   every newsroom makes with its section fronts.

   REGENERATING

     node scripts/og.js          # rewrites assets/og/*.png

   Run it after changing the design, the palette, or the card list —
   then commit the PNGs. seo.js does not invoke it; a build with no
   Chrome present must still produce pages.
   ══════════════════════════════════════════════════════════════ */

