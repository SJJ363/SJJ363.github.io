/* Chrome, wherever this machine keeps it. Linux names come first so a
   CI shell can render too if someone ever wants that; macOS is where
   this is actually run. */
const CHROME_CANDIDATES = [
  process.env.CHROME_PATH,
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Chromium.app/Contents/MacOS/Chromium",
  "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium-browser",
  "/usr/bin/chromium",
].filter(Boolean);

function findChrome() {
  for (const p of CHROME_CANDIDATES) if (fs.existsSync(p)) return p;
  return null;
}

function shoot(chrome, html, out, w, h) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "og-"));
  const page = path.join(tmp, "card.html");
  fs.writeFileSync(page, html);
  try {
    execFileSync(
      chrome,
      [
        "--headless",
        "--disable-gpu",
        "--no-sandbox",
        "--hide-scrollbars",
        "--force-device-scale-factor=1",
        // Web fonts are fetched over the network; without a virtual-time
        // budget Chrome screenshots the fallback serif and the card ships
        // looking like a default browser page.
        "--virtual-time-budget=10000",
        `--window-size=${w},${h}`,
        `--screenshot=${out}`,
        `file://${page}`,
      ],
      { stdio: ["ignore", "ignore", "pipe"] }
    );
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

function build() {
  const chrome = findChrome();
  if (!chrome) {
    console.error(
      "  ! no Chrome/Chromium found — set CHROME_PATH to a browser binary.\n" +
        "    Cards are committed PNGs; the existing ones stay valid until this runs."
    );
    process.exit(1);
  }
  fs.mkdirSync(OUT, { recursive: true });
  console.log(`\nSocial cards → assets/og/  (${path.basename(chrome)})\n`);

  let bytes = 0;
  for (const card of CARDS) {
    const out = path.join(OUT, `${card.id}.png`);
    shoot(chrome, cardHtml(card), out, W, H);
    const size = fs.statSync(out).size;
    bytes += size;
    console.log(`  ✓ ${card.id}.png`.padEnd(34) + `${(size / 1024).toFixed(0)} KB`);
  }

  const logo = path.join(ROOT, "assets", "logo.png");
  shoot(chrome, logoHtml(512), logo, 512, 512);
  console.log(`  ✓ logo.png (512×512)`.padEnd(34) + `${(fs.statSync(logo).size / 1024).toFixed(0)} KB`);

  console.log(
    `\n  ${CARDS.length} cards at ${W}×${H}, ${(bytes / 1024).toFixed(0)} KB total\n`
  );
}

module.exports = { cardFor, CARDS, W, H, OUT };

if (require.main === module) build();
